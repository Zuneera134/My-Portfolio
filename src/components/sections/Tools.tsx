export default function Tools() {
  const itemRefs = useRef<(HTMLDivElement | null)[]>([]);

  useEffect(() => {
    const tweens = itemRefs.current
      .filter((item): item is HTMLDivElement => !!item)
      .map((item) =>
        gsap.fromTo(
          item,
          { opacity: 0, y: 20 },
          {
            opacity: 1,
            y: 0,
            duration: 0.6,
            ease: "power3.out",
            scrollTrigger: {
              trigger: item,
              start: "top 92%",
              once: true,
            },
          }
        )
      );

    return () => {
      tweens.forEach((t) => {
        t.scrollTrigger?.kill();
        t.kill();
      });
    };
  }, []);

  return (
    <section id="tools" className="section section-padding">
      <div className="section-inner">
        <div className="section-eyebrow">What I build with</div>
        <h2 className="section-title">Tools</h2>
        <p className="section-sub">
          The tools and platforms I use every day to code, collaborate and ship.
        </p>

        <div className="mt-12 grid grid-cols-2 sm:grid-cols-4 lg:grid-cols-7 gap-4">
          {TOOLS.map((tool, i) => (
            <div
              key={tool.name}
              ref={(el) => { itemRefs.current[i] = el; }}
              className="card group flex flex-col items-center justify-center gap-4 py-8 hover:border-accent transition-colors"
            >
              <span className="w-14 h-14 rounded-full border border-border group-hover:border-accent flex items-center justify-center group-hover:bg-accent/5 transition-colors">
                <span className="flex items-center justify-center w-[28px] h-[28px]"><Icon path={tool.path} color={tool.color} /></span>
              </span>
              <span className="text-sm font-medium text-fg text-center">{tool.name}</span>
            </div>
          ))}
        </div>
      </div>
    </section>
  );
}
